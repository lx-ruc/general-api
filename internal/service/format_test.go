package service

import "testing"

// YuanString 与前端 fmtYuan 同规则：≥1 元两位小数；不足 1 元至多 4 位（尾零剥掉）；负数带符号
func TestYuanString(t *testing.T) {
	cases := []struct {
		points, ppy int64
		want        string
	}{
		{0, 1_000_000, "¥0"},            // 零
		{2_000_000, 1_000_000, "¥2.00"}, // 整元
		{250_000, 1_000_000, "¥0.25"},   // 不足 1 元：剥尾零
		{123_400, 1_000_000, "¥0.1234"}, // 不足 1 元：满 4 位
		{123_000, 1_000_000, "¥0.123"},  // 3 位
		{10, 1_000_000, "¥0"},           // 超精度（0.00001）舍入后剥成 ¥0
		{-1_000_000, 1_000_000, "-¥1.00"},
		{-250_000, 1_000_000, "-¥0.25"},
		{1_500_000, 500_000, "¥3.00"}, // 自定义汇率
		{250_000, 0, "¥0.25"},         // ppy 非法回退默认 1M
		{999_999, 1_000_000, "¥1"}, // 0.999999 元按 4 位舍入到 1 后剥尾零（与前端 fmtYuan 一致）
	}
	for _, c := range cases {
		if got := YuanString(c.points, c.ppy); got != c.want {
			t.Fatalf("YuanString(%d, %d) = %q, want %q", c.points, c.ppy, got, c.want)
		}
	}
}
