var schemaSQL string

// migrateLockKey PG 迁移咨询锁的固定键（任意稳定常量，仅用于串行化并发迁移）
const migrateLockKey = 74274157701

// WithAdvisoryLock PG 下用事务级咨询锁串行化执行 fn——多实例并发首启时
// check-then-insert 类启动写入（建表、自举管理员等）的竞态兜底；
// 后来者阻塞等锁，见到的已是前者提交后的状态。非 PG 单实例部署直接执行。
func WithAdvisoryLock(db *gorm.DB, key int64, fn func(tx *gorm.DB) error) error {
	if Dialect != "postgres" {
		return fn(db)
	}
	return db.Transaction(func(tx *gorm.DB) error {
		if err := tx.Exec("SELECT pg_advisory_xact_lock(?)", key).Error; err != nil {
			return fmt.Errorf("pg_advisory_xact_lock: %w", err)
		}
		return fn(tx)
	})
}

// Migrate 幂等执行建表语句（按 ; 切分，剔除注释行后逐条执行）。
// schema.sql 以 SQLite 方言书写；postgres 模式在执行前做模板替换：
//
//	INTEGER PRIMARY KEY AUTOINCREMENT → BIGINT GENERATED BY DEFAULT AS IDENTITY
//	（BY DEFAULT 允许显式插 id，供 -migrate-from-sqlite 搬数据）
//	INTEGER → BIGINT（额度/成本可能超出 int4）
//	PRAGMA 语句跳过（PG 外键约束默认即时生效）
//
// PG 下整体放进单事务并先取事务级咨询锁：多实例同时首启（如 docker-compose
// gateway×2 对着新库）时串行化迁移，避免 CREATE TABLE 并发竞态
// （pg_type 重复键）；后来者拿锁后执行的全是幂等 no-op。
func Migrate(db *gorm.DB) error {
	return WithAdvisoryLock(db, migrateLockKey, migrateAll)
}

func migrateAll(db *gorm.DB) error {
	for _, stmt := range splitStatements(schemaSQL) {
		if Dialect == "postgres" {
			if strings.HasPrefix(strings.ToUpper(stmt), "PRAGMA") {
				continue
			}
			stmt = strings.ReplaceAll(stmt, "INTEGER PRIMARY KEY AUTOINCREMENT",
				"BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
			stmt = strings.ReplaceAll(stmt, " INTEGER", " BIGINT")
		}
		if err := db.Exec(stmt).Error; err != nil {
			return fmt.Errorf("migrate %q: %w", truncate(stmt, 60), err)
		}
	}
	// 已有库的幂等加列（CREATE TABLE IF NOT EXISTS 不会更新旧表结构）
	alters := [][3]string{
		{"users", "email", "TEXT NOT NULL DEFAULT ''"},
		{"models", "cost_input_price", "INTEGER NOT NULL DEFAULT 0"},
		{"models", "cost_output_price", "INTEGER NOT NULL DEFAULT 0"},
		{"models", "input_cache_hit_price", "INTEGER NOT NULL DEFAULT 0"},
		{"models", "cost_input_cache_hit_price", "INTEGER NOT NULL DEFAULT 0"},
		{"models", "auto_disabled_at", "INTEGER NOT NULL DEFAULT 0"},
		{"usage_logs", "cached_tokens", "INTEGER NOT NULL DEFAULT 0"},
		{"usage_logs", "input_cache_hit_price", "INTEGER NOT NULL DEFAULT 0"},
		{"usage_logs", "cost_input_cache_hit_price", "INTEGER NOT NULL DEFAULT 0"},
		{"usage_logs", "cost_input_price", "INTEGER NOT NULL DEFAULT 0"},
		{"usage_logs", "cost_output_price", "INTEGER NOT NULL DEFAULT 0"},
		{"usage_logs", "vendor_cost", "INTEGER NOT NULL DEFAULT 0"},
		{"usage_logs", "cache_hit", "INTEGER NOT NULL DEFAULT 0"},
		{"orgs", "require_cost_center", "INTEGER NOT NULL DEFAULT 0"},
		{"api_keys", "cost_center_id", "INTEGER"},
		{"usage_logs", "cost_center_id", "INTEGER"},
		{"orgs", "alert_levels", "TEXT NOT NULL DEFAULT '[80]'"},
		{"orgs", "alert_level", "INTEGER NOT NULL DEFAULT 0"},
		{"orgs", "alert_since", "INTEGER NOT NULL DEFAULT 0"},
		{"orgs", "alert_balance", "INTEGER NOT NULL DEFAULT 0"},
		{"orgs", "alert_balance_hit", "INTEGER NOT NULL DEFAULT 0"},
		{"period_balances", "points_per_yuan", "INTEGER NOT NULL DEFAULT 0"},
		{"users", "alert_levels", "TEXT NOT NULL DEFAULT '[80]'"},
		{"users", "alert_level", "INTEGER NOT NULL DEFAULT 0"},
		{"users", "alert_since", "INTEGER NOT NULL DEFAULT 0"},
		{"users", "alert_balance", "INTEGER NOT NULL DEFAULT 0"},
		{"users", "alert_balance_hit", "INTEGER NOT NULL DEFAULT 0"},
		{"orgs", "contact_name", "TEXT NOT NULL DEFAULT ''"},
		{"orgs", "contact_phone", "TEXT NOT NULL DEFAULT ''"},
		{"orgs", "monthly_quota", "INTEGER NOT NULL DEFAULT 0"},
		{"orgs", "monthly_cost", "INTEGER NOT NULL DEFAULT 0"},
		{"orgs", "monthly_period", "TEXT NOT NULL DEFAULT ''"},
		{"users", "monthly_quota", "INTEGER NOT NULL DEFAULT 0"},
		{"users", "monthly_cost", "INTEGER NOT NULL DEFAULT 0"},
		{"users", "monthly_period", "TEXT NOT NULL DEFAULT ''"},
		{"api_keys", "key_enc", "TEXT NOT NULL DEFAULT ''"},
		{"access_tokens", "token_enc", "TEXT NOT NULL DEFAULT ''"},
		{"channels", "auto_disabled_at", "INTEGER NOT NULL DEFAULT 0"},
		{"channels", "nokey_disabled_at", "INTEGER NOT NULL DEFAULT 0"},
		{"quota_requests", "kind", "TEXT NOT NULL DEFAULT 'quota'"},
		{"quota_requests", "model_names", "TEXT NOT NULL DEFAULT ''"},
		{"users", "is_super", "INTEGER NOT NULL DEFAULT 0"},
		{"models", "type", "TEXT NOT NULL DEFAULT 'chat'"},
		{"channels", "vendor_id", "INTEGER NOT NULL DEFAULT 0"},
		{"models", "vendor_id", "INTEGER NOT NULL DEFAULT 0"},
	}
	for _, a := range alters {
		if !columnExists(db, a[0], a[1]) {
			if err := db.Exec(fmt.Sprintf("ALTER TABLE %s ADD COLUMN %s %s", a[0], a[1], a[2])).Error; err != nil {
				return fmt.Errorf("alter %s.%s: %w", a[0], a[1], err)
			}
		}
	}
	// 已下线功能的存量列幂等删除（打折功能 orgs.discount_permille 已整体移除）
	drops := [][2]string{
		{"orgs", "discount_permille"},
	}
	for _, d := range drops {
		if columnExists(db, d[0], d[1]) {
			if err := db.Exec(fmt.Sprintf("ALTER TABLE %s DROP COLUMN %s", d[0], d[1])).Error; err != nil {
				return fmt.Errorf("drop %s.%s: %w", d[0], d[1], err)
			}
		}
	}
	// users.email 唯一部分索引：闭合「两人并发绑同一邮箱」在 PG READ COMMITTED 下的
	// check-then-act 竞态（应用层查重在 PG 下有快照窗口，SQLite 单写者天然串行）。
	// 必须先去重再建索引，否则存量脏数据会让 CREATE UNIQUE INDEX 失败卡死启动；
	// 去重保留最早注册者，与找回流程「ORDER BY id LIMIT 1」同口径。语句两方言中立、幂等。
	if res := db.Exec(`UPDATE users SET email = '' WHERE email != '' AND id NOT IN
		(SELECT MIN(id) FROM users WHERE email != '' GROUP BY email)`); res.Error != nil {
		return fmt.Errorf("dedupe users.email: %w", res.Error)
	} else if res.RowsAffected > 0 {
		slog.Warn("users.email 存量重复已去重（保留最早绑定者）", "cleared", res.RowsAffected)
	}
	if err := db.Exec(`CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email
		ON users(email) WHERE email != ''`).Error; err != nil {
		return fmt.Errorf("create idx_users_email: %w", err)
	}
	// 存量库首次引入平台层超管分层：尚无超管时把最早的 platform_admin 提升为超管。
	// 必须可重复执行（-migrate-from-sqlite 搬数据进程在自举前 return，旧源库无此列
	// 全部落 0，搬完后的下一次正常启动仍靠这里补提升）；提升后 NOT EXISTS 恒假即 no-op。
	if err := db.Exec(`UPDATE users SET is_super = 1
		WHERE role = 'platform_admin'
		  AND NOT EXISTS (SELECT 1 FROM users WHERE is_super = 1)
		  AND id = (SELECT MIN(id) FROM users WHERE role = 'platform_admin')`).Error; err != nil {
		return fmt.Errorf("promote super admin: %w", err)
	}
	// 文案修正（幂等）：预置模型备注的计价单位「元/百万token」统一为「元/M token」
	if err := db.Exec(`UPDATE models SET remark = replace(remark, '元/百万token', '元/M token')
		WHERE remark LIKE '%元/百万token%'`).Error; err != nil {
		return fmt.Errorf("fix models remark: %w", err)
	}
	// 类型回填（幂等）：存量库引入 models.type 时按名字启发把向量模型标出来；
	// 回填后行 type≠'chat'，WHERE 不再命中即 no-op。chat/video 由管理员在管理台设置
	if err := db.Exec(`UPDATE models SET type = 'embedding'
		WHERE type = 'chat' AND lower(name) LIKE '%embedding%'`).Error; err != nil {
		return fmt.Errorf("backfill models.type: %w", err)
	}

	// ---- 厂商实体化存量迁移（①-⑦，全部幂等；每步以「行内状态」为锚点，崩溃重跑收敛）----
	if err := migrateVendors(db); err != nil {
		return err
	}
	if err := migrateVendorKeys(db); err != nil {
		return err
	}
	// ---- 厂商化遗留列/表清理（必须在迁移序列之后：①还读 channels.vendor 建实体）----
	for _, d := range [][2]string{
		{"channels", "upstream_key_enc"}, // legacy 单 Key 已迁入厂商池（⑦）
		{"channels", "vendor"},           // 渠道归属以 vendor_id 为准（①已消费完文本标签）
		{"models", "vendor"},             // 模型归属以 vendor_id 为准
	} {
		if columnExists(db, d[0], d[1]) {
			if err := db.Exec(fmt.Sprintf("ALTER TABLE %s DROP COLUMN %s", d[0], d[1])).Error; err != nil {
				return fmt.Errorf("drop %s.%s: %w", d[0], d[1], err)
			}
		}
	}
	if err := db.Exec("DROP TABLE IF EXISTS channel_keys").Error; err != nil { // Key 池已上提厂商（⑥）
		return fmt.Errorf("drop channel_keys: %w", err)
	}
	return nil
}

// migrateVendors 厂商实体化存量迁移（建实体/回填归属/合并拆分副本/折算授权）。
// 每条语句幂等：①ON CONFLICT ②vendor_id=0 锚点 ③NOT EXISTS 锚点 ④vendor_id=0 锚点
// ⑤ON CONFLICT。新库（无渠道/模型）全部自然 no-op
func migrateVendors(db *gorm.DB) error {
	now := time.Now().Unix()
	// ③（政策修正）：合并批一拆分的 -berry 副本回原名——同一模型现可跨厂商承接
	// （各自 Key 池路由、主厂商定价）。仅当副本存在时执行；合并后副本消失即幂等锚点
	const (
		mergeBase = "deepseek-v4-1-flash-261017"
		mergeCopy = "deepseek-v4-1-flash-261017-berry"
	)
	var hasCopy int64
	_ = db.Raw(`SELECT COUNT(*) FROM models WHERE name = '`+mergeCopy+`'`).Scan(&hasCopy).Error
	if hasCopy > 0 {
		// 副本端点能力改回原名（原名的同渠道能力不存在——拆分时是整体挪移）
		if err := db.Exec(`UPDATE channel_abilities SET model_name = '`+mergeBase+`'
			WHERE model_name = '`+mergeCopy+`'`).Error; err != nil {
			return fmt.Errorf("merge abilities back: %w", err)
		}
		// 客户开通/子账号例外/覆盖价：并回原名（原名已有的保留原名值），残留行删除
		for _, stmt := range []string{
			`INSERT INTO org_model_grants (org_id, model_name, granted_by, source, created_at)
			SELECT org_id, '` + mergeBase + `', granted_by, source, created_at FROM org_model_grants
			WHERE model_name = '` + mergeCopy + `' ON CONFLICT(org_id, model_name) DO NOTHING`,
			`DELETE FROM org_model_grants WHERE model_name = '` + mergeCopy + `'`,
			`INSERT INTO user_model_grants (user_id, model_name, granted_by, created_at)
			SELECT user_id, '` + mergeBase + `', granted_by, created_at FROM user_model_grants
			WHERE model_name = '` + mergeCopy + `' ON CONFLICT(user_id, model_name) DO NOTHING`,
			`DELETE FROM user_model_grants WHERE model_name = '` + mergeCopy + `'`,
			`INSERT INTO org_model_prices (org_id, model_name, input_price, output_price,
				input_cache_hit_price, remark, created_at, updated_at)
			SELECT org_id, '` + mergeBase + `', input_price, output_price,
				input_cache_hit_price, remark, created_at, updated_at FROM org_model_prices
			WHERE model_name = '` + mergeCopy + `' ON CONFLICT(org_id, model_name) DO NOTHING`,
			`DELETE FROM org_model_prices WHERE model_name = '` + mergeCopy + `'`,
			`DELETE FROM models WHERE name = '` + mergeCopy + `'`,
		} {
			if err := db.Exec(stmt).Error; err != nil {
				return fmt.Errorf("merge copy back: %w", err)
			}
		}
		slog.Info("已合并拆分副本回原名（同名模型跨厂商承接）", "copy", mergeCopy, "base", mergeBase)
	}
	// 新库/已迁移库：channels.vendor 文本列已不存在（新库 schema 无此列，存量库上方已删）
	// → ①②④⑤ 的文本标签消费天然 no-op，跳过（③ 合并在列守卫之前，始终有机会执行）
	if !columnExists(db, "channels", "vendor") {
		return nil
	}
	// ① 非空 vendor 标签建厂商实体；空标签渠道归并到「未分类」（仅当存在时才建）
	if err := db.Exec(`INSERT INTO vendors (name, display_name, status, remark, created_at, updated_at)
		SELECT DISTINCT vendor, vendor, 1, '迁移自渠道厂商标签', CAST(? AS INTEGER), CAST(? AS INTEGER) FROM channels
		WHERE vendor <> '' ON CONFLICT(name) DO NOTHING`, now, now).Error; err != nil {
		return fmt.Errorf("migrate vendors seed: %w", err)
	}
	if err := db.Exec(`INSERT INTO vendors (name, display_name, status, remark, created_at, updated_at)
		SELECT DISTINCT 'uncategorized', '未分类', 1, '空厂商标签渠道归并', CAST(? AS INTEGER), CAST(? AS INTEGER) FROM channels
		WHERE vendor = '' ON CONFLICT(name) DO NOTHING`, now, now).Error; err != nil {
		return fmt.Errorf("migrate vendors uncategorized: %w", err)
	}
	// ② 回填渠道归属（锚点 vendor_id=0）
	if err := db.Exec(`UPDATE channels SET vendor_id = (
			SELECT v.id FROM vendors v WHERE v.name = COALESCE(NULLIF(channels.vendor, ''), 'uncategorized'))
		WHERE vendor_id = 0`).Error; err != nil {
		return fmt.Errorf("migrate channels.vendor_id: %w", err)
	}
	// ④ 模型主厂商回填：按承接渠道优先级确定性取一（跨厂商模型的主厂商=优先级最高
	// 的承接厂商，用于厂商价层级与展示分组）
	if err := db.Exec(`UPDATE models SET vendor_id = (
			SELECT c.vendor_id FROM channel_abilities a JOIN channels c ON c.id = a.channel_id
			WHERE a.model_name = models.name ORDER BY c.priority DESC, c.id LIMIT 1)
		WHERE vendor_id = 0
			AND EXISTS (SELECT 1 FROM channel_abilities a WHERE a.model_name = models.name)`).Error; err != nil {
		return fmt.Errorf("migrate models.vendor_id: %w", err)
	}
		// ⑤ 存量授权折算成厂商级（DISTINCT 去重：同客户多模型同厂商只留一行；
	// 模型级 org_model_grants/user_model_grants 行保留为例外，不删除）
	if err := db.Exec(`INSERT INTO org_vendor_grants (org_id, vendor_id, source, created_at)
		SELECT DISTINCT g.org_id, m.vendor_id, 'backfill', CAST(? AS INTEGER) FROM org_model_grants g
		JOIN models m ON m.name = g.model_name
		WHERE m.vendor_id > 0 ON CONFLICT(org_id, vendor_id) DO NOTHING`, now).Error; err != nil {
		return fmt.Errorf("migrate org_vendor_grants: %w", err)
	}
	if err := db.Exec(`INSERT INTO user_vendor_grants (user_id, vendor_id, created_at)
		SELECT DISTINCT g.user_id, m.vendor_id, CAST(? AS INTEGER) FROM user_model_grants g
		JOIN models m ON m.name = g.model_name
		WHERE m.vendor_id > 0 ON CONFLICT(user_id, vendor_id) DO NOTHING`, now).Error; err != nil {
		return fmt.Errorf("migrate user_vendor_grants: %w", err)
	}
	return nil
}

// migrateVendorKeys Key 池上提搬迁（⑥渠道池行→厂商池行，⑦legacy 单 Key→池行）：
// ⑥ id 原样保留（Redis 冷却 scope 中 keyID 段连续 + NOT EXISTS 天然防重插 + 崩溃安全），
// 密文 SQL 级原样拷贝不经过加解密；⑦ 转池行（权重 1）后清空原列——清空即幂等锚点。
// channel_keys 表与 upstream_key_enc 列的物理删除在 C5 drops 统一执行（过渡期双写兼容）
func migrateVendorKeys(db *gorm.DB) error {
	now := time.Now().Unix()
	// 新库/已迁移库：channel_keys 已不存在（新库 schema 无此表，存量库上方已删）→ no-op。
	// 方言必须分流后查询——PG 上跑 sqlite_master 会报错并毒死迁移事务（25P02 连坐）
	var hasTable bool
	if Dialect == "postgres" {
		_ = db.Raw(`SELECT COUNT(*) > 0 FROM information_schema.tables WHERE table_name = 'channel_keys'`).Scan(&hasTable).Error
	} else {
		_ = db.Raw("SELECT COUNT(*) > 0 FROM sqlite_master WHERE type = 'table' AND name = 'channel_keys'").Scan(&hasTable).Error
	}
	if !hasTable {
		return nil
	}
	if err := db.Exec(`INSERT INTO vendor_keys (id, vendor_id, key_enc, weight, status, remark, created_at, updated_at)
		SELECT k.id, c.vendor_id, k.key_enc, k.weight, k.status,
			COALESCE(NULLIF(k.remark, ''), '迁移自渠道「' || c.name || '」Key 池'), k.created_at, k.updated_at
		FROM channel_keys k JOIN channels c ON c.id = k.channel_id
		WHERE c.vendor_id > 0 AND NOT EXISTS (SELECT 1 FROM vendor_keys vk WHERE vk.id = k.id)`).Error; err != nil {
		return fmt.Errorf("migrate vendor_keys pool: %w", err)
	}
	if err := db.Exec(`INSERT INTO vendor_keys (vendor_id, key_enc, weight, status, remark, created_at, updated_at)
		SELECT c.vendor_id, c.upstream_key_enc, 1, 1, '迁移自渠道「' || c.name || '」单密钥',
			c.created_at, CAST(? AS INTEGER) FROM channels c
		WHERE c.upstream_key_enc <> '' AND c.vendor_id > 0`, now).Error; err != nil {
		return fmt.Errorf("migrate vendor_keys legacy: %w", err)
	}
	if err := db.Exec(`UPDATE channels SET upstream_key_enc = '' WHERE upstream_key_enc <> ''`).Error; err != nil {
		return fmt.Errorf("clear legacy upstream_key_enc: %w", err)
	}
	return nil
}

// columnExists 方言分支：sqlite 用 pragma_table_info，postgres 用 information_schema
func columnExists(db *gorm.DB, table, column string) bool {
	var cnt int64
	if Dialect == "postgres" {
		_ = db.Raw(`SELECT COUNT(*) FROM information_schema.columns
			WHERE table_name = ? AND column_name = ?`, table, column).Scan(&cnt).Error
	} else {
		_ = db.Raw("SELECT COUNT(*) FROM pragma_table_info(?) WHERE name = ?", table, column).Scan(&cnt).Error
	}
	return cnt > 0
}

func splitStatements(sql string) []string {
	var stmts []string
	for _, part := range strings.Split(sql, ";") {
		var lines []string
		for _, line := range strings.Split(part, "\n") {
			if t := strings.TrimSpace(line); strings.HasPrefix(t, "--") {
				continue
			}
			lines = append(lines, line)
		}
		if st := strings.TrimSpace(strings.Join(lines, "\n")); st != "" {
			stmts = append(stmts, st)
		}
	}
	return stmts
}

func truncate(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[:n] + "..."
}
