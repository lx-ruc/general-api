    <h1 class="doc-h1">账号与密码安全</h1>
    <p class="doc-desc">三级账号的密码修改与邮箱自助找回——绑一次邮箱，忘密码不再需要找管理员。</p>

    <div class="doc-prose">
      <h2>三级账号</h2>
      <ul>
        <li><strong>系统管理员</strong>：管理渠道、模型、定价与全部客户，服务启动时自动创建。</li>
        <li><strong>客户管理员</strong>：客户自助注册（邮箱验证码），或由系统管理员创建；管理本客户的子账号、授权与额度。</li>
        <li><strong>子账号</strong>：由客户管理员创建，用 API key 调用模型，额度受客户与个人双层约束。</li>
      </ul>

      <h2>修改密码</h2>
      <p>三类账号登录后均可修改：顶栏右上角用户菜单 → <strong>「修改密码」</strong>，输入原密码与新密码
        （至少 6 位）即可，全程不需要邮箱。</p>

      <h2>绑定邮箱（找回密码的前提）</h2>
      <p>顶栏用户菜单 → <strong>「个人资料」</strong> → 填写邮箱 → 「发验证码」→ 输入邮箱收到的 6 位验证码
        → 确认绑定。换绑流程相同，需要验证<strong>新</strong>邮箱；换绑后旧邮箱里尚未使用的重置链接立即失效。</p>
      <ul>
        <li>一个邮箱只能绑定一个账号（找回邮件按邮箱发给账号主人，一号一箱防发错人）。</li>
        <li>客户管理员 / 子账号也可以在建号时由管理员预填邮箱（选填）。</li>
        <li>绑定后会额外收到一封「邮箱绑定成功」的通知邮件，并在站内铃铛留下一条不可删除的记录——
          若非本人操作，请立即修改密码并联系管理员。</li>
        <li>除找回密码外，绑定邮箱还会收到额度预警、渠道告警等系统邮件。</li>
      </ul>

      <h2>忘记密码：邮件自助找回</h2>
      <p>登录页 → <strong>「忘记密码」</strong> → 输入绑定的邮箱 → 收到重置链接邮件（30 分钟内有效、
        仅可使用一次）→ 打开链接设置新密码。同一邮箱 60 秒内只发一封；重新申请会使旧链接作废。</p>
      <p><strong>未绑定邮箱的账号</strong>无法自助找回，请联系管理员重置：</p>
      <ul>
        <li>子账号 → 联系本客户管理员（子账号管理 → 重置密码）。</li>
        <li>客户管理员 → 联系系统管理员（客户管理 → 客户详情 → 重置管理员密码）。</li>
        <li>系统管理员 → 服务器上执行 <code>./token-gateway -reset-password 用户名:新密码</code>。</li>
      </ul>

      <h2>安全机制</h2>
      <ul>
        <li>密码 bcrypt 哈希存储；重置令牌与验证码只存哈希 / 服务端，明文不落库。</li>
        <li>验证码 5 分钟有效、错误 5 次作废；发码与找回提交均有限速，防邮件轰炸与暴力尝试。</li>
        <li>登录限速 5 次 / 分 / IP；连续失败的渠道密钥、异常告警均有站内 + 邮件双通道通知。</li>
      </ul>
